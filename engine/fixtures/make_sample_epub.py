#!/usr/bin/env python3
"""生成测试书 fixtures/sample.epub。

内容为自写的中英文各一段（公有领域要求不涉及），用于验证：
- 中文字形能否用 macOS 自带 CJK 字体排出
- 拉丁字母与标点的排版
- 标题 + 段落的分页效果
- 目录（TOC）的层级与页码
- 页内的词矩形与链接（书内锚点 + 外部 URL）

中文段落必须整段写在一行里。HTML 会把段落中间的换行和缩进折叠成一个空格，
而 crengine 没有实现 CSS Text 3 的「两个 CJK 字符之间的空白折叠为无」那条规则
（上游 crengine/src/lvtextfm.cpp 里那段代码是注释掉的），所以段内换行会在
中文句子中间留下一个可见的空格。详见 docs/tasks/ENG-002/notes.md。

英文段落可以折行：折行处折叠出来的空格正好是词间该有的空格。

用法：
    python3 fixtures/make_sample_epub.py
"""

import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "sample.epub")

CONTAINER_XML = """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
"""

CONTENT_OPF = """<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="2.0" unique-identifier="BookId">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:opf="http://www.idpf.org/2007/opf">
    <dc:title>墨阅排版样张</dc:title>
    <dc:creator>墨阅项目组</dc:creator>
    <dc:language>zh-CN</dc:language>
    <dc:identifier id="BookId">urn:uuid:inkread-spike-sample-0001</dc:identifier>
    <dc:description>crengine-ng spike 用的最小测试书，含中英文各一段。</dc:description>
  </metadata>
  <manifest>
    <item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>
    <item id="chapter1" href="chapter1.xhtml" media-type="application/xhtml+xml"/>
    <item id="chapter2" href="chapter2.xhtml" media-type="application/xhtml+xml"/>
    <item id="chapter3" href="chapter3.xhtml" media-type="application/xhtml+xml"/>
  </manifest>
  <spine toc="ncx">
    <itemref idref="chapter1"/>
    <itemref idref="chapter2"/>
    <itemref idref="chapter3"/>
  </spine>
</package>
"""

TOC_NCX = """<?xml version="1.0" encoding="UTF-8"?>
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
  <head>
    <meta name="dtb:uid" content="urn:uuid:inkread-spike-sample-0001"/>
    <meta name="dtb:depth" content="1"/>
    <meta name="dtb:totalPageCount" content="0"/>
    <meta name="dtb:maxPageNumber" content="0"/>
  </head>
  <docTitle>
    <text>墨阅排版样张</text>
  </docTitle>
  <navMap>
    <navPoint id="navpoint-1" playOrder="1">
      <navLabel>
        <text>中文段落</text>
      </navLabel>
      <content src="chapter1.xhtml"/>
    </navPoint>
    <navPoint id="navpoint-2" playOrder="2">
      <navLabel>
        <text>English paragraph</text>
      </navLabel>
      <content src="chapter2.xhtml"/>
    </navPoint>
    <navPoint id="navpoint-3" playOrder="3">
      <navLabel>
        <text>第三章 · 分页检查</text>
      </navLabel>
      <content src="chapter3.xhtml"/>
      <navPoint id="navpoint-3-1" playOrder="4">
        <navLabel>
          <text>第三章 · 注释</text>
        </navLabel>
        <content src="chapter3.xhtml#note-1"/>
      </navPoint>
    </navPoint>
  </navMap>
</ncx>
"""

CHAPTER1 = """<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <title>中文段落</title>
</head>
<body>
  <h1>第一章 · 中文排版</h1>
  <p>电子墨水屏和常见的液晶显示屏不一样：它没有背光，靠黑白颗粒在电场作用下改变状态来显示图文。因此刷新速度慢，但断电后画面依然保留，待机功耗也低得多。</p>
  <p>把书装进墨水屏设备，真正难的地方不在于把文字画出来，而在于把一整本书切成大小合适的页面。行距、字号、页边距、留白，任何一项不合适，长时间阅读都会累。好的排版应当让人忘记设备的存在。</p>
  <p>本文件由脚本自动生成，用于验证排版引擎能否处理中文断行、标点避头尾和段落缩进。</p>
</body>
</html>
"""

CHAPTER2 = """<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <title>English paragraph</title>
</head>
<body>
  <h1>Chapter Two · English</h1>
  <p>An e-ink display has no backlight. It shows a page by driving millions of tiny capsules,
     each of which stays in one of two states until it is changed again. The result is a page
     that looks like paper, survives without power, and costs almost nothing to keep on screen.</p>
  <p>The hard part of a reader is not drawing glyphs, it is deciding where one page ends and the
     next one begins. Line height, type size, margins and hyphenation all matter, and a layout
     that is merely correct can still be tiring to read for a whole chapter.</p>
  <p>This file is generated by a script and used to check Latin typesetting, justification and
     the spacing between words.</p>
</body>
</html>
"""


CHAPTER3 = """<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <title>第三章 · 分页检查</title>
</head>
<body>
  <h1>第三章 · 分页检查</h1>
  <p>这一章没有别的目的，只为让测试书足够长，超过一页，用来验证分页是否正常、页码是否能按顺序取到、以及每一页的内容是否互不重复。本页还放了两个链接：一个指向本章末尾的注释（书内锚点），一个指向站外地址（书外 URL）。<a href="#note-1">[1]</a> <a href="https://example.com/inkread">墨阅项目主页</a></p>
  <p>排版引擎把连续文本切成固定大小的页面。切分的位置由字号、行距、页边距共同决定：改一个数字，整本书的分页都会跟着变。</p>
  <p>对墨水屏来说，分页还牵涉刷新。翻页时如果能只刷新变化的那一小块，体验会好很多；整页全刷则会有明显的黑白闪烁。</p>
  <p>所以这一段、下一段、再下一段，都是长度相近的填充文字，用来把第三页也占满一部分，让「取第 N 页」这条路径在多页文档上真的被走到。</p>
  <p>填充文字一：分页的边界可能落在句子中间，也可能在词中间。中文没有词边界，断行只按字走；英文则要处理连字符和两端对齐。</p>
  <p>填充文字二：同样的文字，在不同字号下会落到不同的页。这一点在调试时很有用，可以用同一段文字对照不同参数下的分页结果。</p>
  <p>填充文字三：最后一页往往只排了一半，剩下的留白。这一页最能看出页边距和页面底部对齐的处理是否正确。</p>
  <p>填充文字四：结束。</p>
  <p id="note-1">[1] 注释：这是书内锚点链接的目标段落。用来验证书内链接能解析出目标位置与目标页码。</p>
</body>
</html>
"""


def main() -> None:
    # mimetype 必须是第一个条目，而且不压缩。
    with zipfile.ZipFile(OUT, "w") as epub:
        epub.writestr(
            zipfile.ZipInfo("mimetype"), "application/epub+zip", compress_type=zipfile.ZIP_STORED
        )
        epub.writestr("META-INF/container.xml", CONTAINER_XML, compress_type=zipfile.ZIP_DEFLATED)
        epub.writestr("OEBPS/content.opf", CONTENT_OPF, compress_type=zipfile.ZIP_DEFLATED)
        epub.writestr("OEBPS/toc.ncx", TOC_NCX, compress_type=zipfile.ZIP_DEFLATED)
        epub.writestr("OEBPS/chapter1.xhtml", CHAPTER1, compress_type=zipfile.ZIP_DEFLATED)
        epub.writestr("OEBPS/chapter2.xhtml", CHAPTER2, compress_type=zipfile.ZIP_DEFLATED)
        epub.writestr("OEBPS/chapter3.xhtml", CHAPTER3, compress_type=zipfile.ZIP_DEFLATED)
    print("已生成：{}（{} 字节）".format(OUT, os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
